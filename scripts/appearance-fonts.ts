// Regenerates the embedded fonts of app.oxitune.appearance: one
// font-<family>.css per family, the latin and latin-ext subsets of its
// variable woff2 from @fontsource-variable as data URLs (the page needs no
// font host), and OFL.txt with every family's copyright line.
//
//   bun scripts/appearance-fonts.ts
//
// Network access to cdn.jsdelivr.net; run it when adding or updating a font,
// then commit the output. Every family must be under the SIL Open Font
// License (checked against its LICENSE file).

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const PLUGIN = join(import.meta.dir, '..', 'plugins', 'app.oxitune.appearance');
const CDN = 'https://cdn.jsdelivr.net/npm/@fontsource-variable';
const SUBSETS = ['latin-ext', 'latin'];

/** Package name -> the family name the stylesheets use. */
export const FAMILIES: Record<string, string> = {
  inter: 'Oxa Inter',
  figtree: 'Oxa Figtree',
  geist: 'Oxa Geist',
  manrope: 'Oxa Manrope',
  'plus-jakarta-sans': 'Oxa Plus Jakarta Sans',
  'dm-sans': 'Oxa DM Sans'
};

async function text(url: string): Promise<string> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}

async function bytes(url: string): Promise<Uint8Array> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return new Uint8Array(await res.arrayBuffer());
}

/** unicode-range of each subset, from fontsource's own stylesheet. */
export function subsetRanges(css: string, pkg: string): Record<string, string> {
  const out: Record<string, string> = {};
  const re = new RegExp(`/\\* ${pkg}-([\\w-]+)-wght-normal \\*/\\s*@font-face\\s*{[^}]*?unicode-range:\\s*([^;]+);`, 'g');
  for (const m of css.matchAll(re)) out[m[1]] = m[2].trim();
  return out;
}

async function main() {
  const copyrights: string[] = [];
  let licenseBody = '';
  for (const [pkg, family] of Object.entries(FAMILIES)) {
    const license = await text(`${CDN}/${pkg}@5/LICENSE`);
    if (!license.includes('SIL Open Font License')) throw new Error(`${pkg} is not under the OFL`);
    copyrights.push(license.split('\n')[0].replace(/\s+\S+\.ttf:.*$/, '').trim());
    if (!licenseBody) licenseBody = license.slice(license.indexOf('This Font Software is licensed'));

    const ranges = subsetRanges(await text(`${CDN}/${pkg}@5/wght.css`), pkg);
    const parts = [
      `/* ${family}: ${pkg} variable (weights 100-900) under the SIL Open Font\n` +
        `   License 1.1 (OFL.txt), from @fontsource-variable/${pkg}@5, latin and\n` +
        `   latin-ext subsets embedded so the page needs no font host. Generated by\n` +
        `   scripts/appearance-fonts.ts; do not edit by hand. */\n`
    ];
    for (const subset of SUBSETS) {
      if (!ranges[subset]) throw new Error(`${pkg}: no ${subset} subset`);
      const data = Buffer.from(await bytes(`${CDN}/${pkg}@5/files/${pkg}-${subset}-wght-normal.woff2`)).toString('base64');
      parts.push(
        `@font-face {\n  font-family: '${family}';\n  font-style: normal;\n  font-display: swap;\n  font-weight: 100 900;\n` +
          `  src: url(data:font/woff2;base64,${data}) format('woff2-variations');\n  unicode-range: ${ranges[subset]};\n}\n`
      );
    }
    writeFileSync(join(PLUGIN, `font-${pkg}.css`), parts.join('\n'));
    console.log(`font-${pkg}.css`);
  }
  writeFileSync(join(PLUGIN, 'OFL.txt'), copyrights.join('\n') + '\n\n' + licenseBody);
}

if (import.meta.main) await main();
